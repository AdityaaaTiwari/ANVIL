function yamlValue(value: string): string {
  return /^[\w .,()/'-]*$/.test(value) && !value.includes(": ") ? value : JSON.stringify(value);
}

function frontmatter(entries: Array<[string, string | undefined]>): string {
  const lines = entries
    .filter(([, value]) => value !== undefined && value !== "")
    .map(([key, value]) => `${key}: ${yamlValue(value as string)}`);
  return `---\n${lines.join("\n")}\n---\n\n`;
}

const GENERATED_NOTE = (item: CatalogItem) =>
  `<!-- Generated by ANVIL from catalog/${item.sourcePath}. Re-run \`anvil install\` to update. -->\n\n`;

/** Markdown frontmatter-free body with a generated note. */
const body = (item: CatalogItem) => GENERATED_NOTE(item) + item.body + "\n";

function claudeFiles(item: CatalogItem): PlannedFile[] {
  const note = GENERATED_NOTE(item);
  switch (item.kind) {
    case "agent":
      return [
        {
          path: `.claude/agents/anvil-${item.id}.md`,
          content:
            frontmatter([
              ["name", `anvil-${item.id}`],
              ["description", item.description],
              ["tools", item.tools?.join(", ")],
            ]) +
            note +
            item.body +
            "\n",
          targets: ["claude"],
        },
      ];
    case "skill":
      return [
        {
          path: `.claude/skills/anvil-${item.id}/SKILL.md`,
          content:
            frontmatter([
              ["name", `anvil-${item.id}`],
              ["description", item.description],
            ]) +
            note +
            item.body +
            "\n",
          targets: ["claude"],
        },
      ];
    case "command":
      return [
        {
          path: `.claude/commands/anvil/${item.id}.md`,
          content:
            frontmatter([
              ["description", item.description],
              ["argument-hint", item.argumentHint],
            ]) +
            note +
            item.body +
            "\n",
          targets: ["claude"],
        },
      ];
    case "rule":
      return [
        {
          path: `.claude/rules/anvil/${item.language ?? "common"}/${item.id}.md`,
          content: (item.globs ? frontmatter([["paths", item.globs.join(", ")]]) : "") + note + item.body + "\n",
          targets: ["claude"],
        },
      ];
  }
}

function cursorFiles(item: CatalogItem): PlannedFile[] {
  const note = GENERATED_NOTE(item);
  if (item.kind === "command") {
    return [{ path: `.cursor/commands/anvil-${item.id}.md`, content: note + item.body + "\n", targets: ["cursor"] }];
  }
  const prefix = item.kind === "rule" ? `anvil-${item.language ?? "common"}` : `anvil-${item.kind}`;
  const alwaysApply = item.kind === "rule" && (item.language ?? "common") === "common" && !item.globs;
  const description = item.kind === "agent" ? `Act as the ANVIL ${item.name}: ${item.description}` : item.description;
  return [
    {
      path: `.cursor/rules/${prefix}-${item.id}.mdc`,
      content:
        frontmatter([
          ["description", description],
          ["globs", item.globs?.join(",")],
          ["alwaysApply", alwaysApply ? "true" : "false"],
        ]) +
        note +
        item.body +
        "\n",
      targets: ["cursor"],
    },
  ];
}

/** Shared Markdown copies referenced from AGENTS.md / GEMINI.md. */
function sharedFile(item: CatalogItem, target: HarnessTarget): PlannedFile | undefined {
  const folder = item.kind === "rule" ? `rules/${item.language ?? "common"}` : `${item.kind}s`;
  if (item.kind === "skill") return undefined;
  return {
    path: `${ANVIL_STATE_DIR}/harness/${folder}/${item.id}.md`,
    content: GENERATED_NOTE(item) + item.body + "\n",
    targets: [target],
  };
}

function sharedSkill(item: CatalogItem, target: HarnessTarget): PlannedFile {
  return {
    path: `.agents/skills/anvil-${item.id}/SKILL.md`,
    content:
      frontmatter([
        ["name", `anvil-${item.id}`],
        ["description", item.description],
      ]) +
      GENERATED_NOTE(item) +
      item.body +
      "\n",
    targets: [target],
  };
}

function opencodeFiles(item: CatalogItem): PlannedFile[] {
  const note = GENERATED_NOTE(item);
  if (item.kind === "agent") {
    return [
      {
        path: `.opencode/agent/anvil-${item.id}.md`,
        content:
          frontmatter([
            ["description", item.description],
            ["mode", "subagent"],
          ]) +
          note +
          item.body +
          "\n",
        targets: ["opencode"],
      },
    ];
  }
  if (item.kind === "command") {
    return [
      {
        path: `.opencode/command/anvil-${item.id}.md`,
        content: frontmatter([["description", item.description]]) + note + item.body + "\n",
        targets: ["opencode"],
      },
    ];
  }
  return [];
}

function geminiFiles(item: CatalogItem): PlannedFile[] {
  if (item.kind !== "command") return [];
  // JSON string escapes are a subset of TOML basic-string escapes.
  // Gemini CLI substitutes `{{args}}` where Claude Code and OpenCode use `$ARGUMENTS`.
  const prompt = item.body.replaceAll("$ARGUMENTS", "{{args}}");
  return [
    {
      path: `.gemini/commands/anvil/${item.id}.toml`,
      content: `# Generated by ANVIL from catalog/${item.sourcePath}\ndescription = ${JSON.stringify(item.description)}\nprompt = ${JSON.stringify(prompt)}\n`,
      targets: ["gemini"],
    },
  ];
}

function sharedFiles(item: CatalogItem, target: HarnessTarget): PlannedFile[] {
  const shared = sharedFile(item, target);
  return [...(shared ? [shared] : []), ...(item.kind === "skill" ? [sharedSkill(item, target)] : [])];
}

function copilotFiles(item: CatalogItem): PlannedFile[] {
  switch (item.kind) {
    case "rule": {
      const language = item.language ?? "common";
      return [
        {
          path: `.github/instructions/anvil-${language}-${item.id}.instructions.md`,
          content:
            frontmatter([
              ["description", item.description],
              ["applyTo", item.globs?.join(",") ?? (language === "common" ? "**" : undefined)],
            ]) + body(item),
          targets: ["copilot"],
        },
      ];
    }
    case "command":
      return [
        {
          path: `.github/prompts/anvil-${item.id}.prompt.md`,
          content:
            frontmatter([
              ["description", item.description],
              ["mode", "agent"],
            ]) + body(item).replaceAll("$ARGUMENTS", "${input:args}"),
          targets: ["copilot"],
        },
      ];
    case "agent":
      return [
        {
          path: `.github/agents/anvil-${item.id}.agent.md`,
          content:
            frontmatter([
              ["name", `anvil-${item.id}`],
              ["description", item.description],
            ]) + body(item),
          targets: ["copilot"],
        },
      ];
    case "skill":
      return [];
  }
}

function windsurfFiles(item: CatalogItem): PlannedFile[] {
  if (item.kind === "command") {
    return [
      {
        path: `.windsurf/workflows/anvil-${item.id}.md`,
        content: frontmatter([["description", item.description]]) + body(item),
        targets: ["windsurf"],
      },
    ];
  }
  if (item.kind !== "rule") return [];
  const language = item.language ?? "common";
  const trigger = item.globs ? "glob" : language === "common" ? "always_on" : "model_decision";
  return [
    {
      path: `.windsurf/rules/anvil-${language}-${item.id}.md`,
      content:
        frontmatter([
          ["trigger", trigger],
          ["description", item.description],
          ["globs", item.globs?.join(",")],
        ]) + body(item),
      targets: ["windsurf"],
    },
  ];
}

function kiroFiles(item: CatalogItem): PlannedFile[] {
  if (item.kind === "rule") {
    const language = item.language ?? "common";
    const inclusion = item.globs ? "fileMatch" : language === "common" ? "always" : "manual";
    return [
      {
        path: `.kiro/steering/anvil-${language}-${item.id}.md`,
        content:
          frontmatter([
            ["inclusion", inclusion],
            ["fileMatchPattern", item.globs?.join(",")],
          ]) + body(item),
        targets: ["kiro"],
      },
    ];
  }
  if (item.kind === "skill") return [];
  // Agents and workflows become manual steering files the user pulls in with `#anvil-<kind>-<id>`.
  return [
    {
      path: `.kiro/steering/anvil-${item.kind}-${item.id}.md`,
      content: frontmatter([["inclusion", "manual"]]) + `# ${item.name}\n\n${item.description}\n\n` + body(item),
      targets: ["kiro"],
    },
  ];
}

function clineFiles(item: CatalogItem): PlannedFile[] {
  if (item.kind === "command") {
    return [{ path: `.clinerules/workflows/anvil-${item.id}.md`, content: body(item), targets: ["cline"] }];
  }
  if (item.kind !== "rule") return [];
  const language = item.language ?? "common";
  return [
    {
      path: `.clinerules/anvil-${language}-${item.id}.md`,
      content: (item.globs ? frontmatter([["paths", item.globs.join(", ")]]) : "") + body(item),
      targets: ["cline"],
    },
  ];
}

/** Files for each target: native formats plus the shared copies the instruction blocks point at. */
function renderTarget(target: HarnessTarget, item: CatalogItem): PlannedFile[] {
  switch (target) {
    case "claude":
      return claudeFiles(item);
    case "cursor":
      return cursorFiles(item);
    case "opencode":
      return [...opencodeFiles(item), ...sharedFiles(item, target)];
    case "codex":
      return sharedFiles(item, target);
    case "gemini":
      return [...geminiFiles(item), ...sharedFiles(item, target)];
    case "copilot":
      return [...copilotFiles(item), ...sharedFiles(item, target)];
    case "windsurf":
      return [...windsurfFiles(item), ...sharedFiles(item, target)];
    case "kiro":
      return [...kiroFiles(item), ...sharedFiles(item, target)];
    case "cline":
      return [...clineFiles(item), ...sharedFiles(item, target)];
    case "zed":
    default:
      return sharedFiles(item, target);
  }
}

/** Managed instruction blocks each target reads. */
const TARGET_BLOCK_FILES: Partial<Record<HarnessTarget, string[]>> = {
  codex: ["AGENTS.md"],
  opencode: ["AGENTS.md"],
  gemini: ["GEMINI.md"],
  copilot: [".github/copilot-instructions.md"],
  windsurf: ["AGENTS.md"],
  kiro: [".kiro/steering/anvil-harness.md"],
  cline: [".clinerules/anvil-harness.md"],
  zed: ["AGENTS.md"],
};

/** First clause of a description, capped, for always-loaded indexes. */
function brief(description: string, max = 72): string {
  const clause = description.split(/(?<=[a-z0-9)])[;:.](?:\s|$)| — /)[0]?.trim() ?? description;
  return clause.length <= max ? clause : clause.slice(0, max - 1).replace(/[\s,]+\S*$/, "") + "…";
}

function instructionsBlock(items: CatalogItem[], skillsPath: string): string {
  const agents = items.filter((i) => i.kind === "agent");
  const commands = items.filter((i) => i.kind === "command");
  const skills = items.filter((i) => i.kind === "skill");
  const commonRules = items.filter((i) => i.kind === "rule" && (i.language ?? "common") === "common");
  const languageRules = items.filter((i) => i.kind === "rule" && (i.language ?? "common") !== "common");
  const lines: string[] = [
    "## ANVIL engineering harness",
    "",
    "ANVIL installed these project instructions. Prefer evidence over assumption: never claim a check passed unless it was run.",
    "",
  ];
  if (commonRules.length) {
    lines.push("### Always-on rules", "");
    for (const rule of commonRules) {
      lines.push(
        `- **${rule.name}** — ${rule.description} (\`${ANVIL_STATE_DIR}/harness/rules/common/${rule.id}.md\`)`
      );
    }
    lines.push("");
  }
  if (languageRules.length) {
    lines.push("### Language rules (read before editing matching files)", "");
    for (const rule of languageRules) {
      lines.push(
        `- ${rule.language}: **${rule.name}**${rule.globs ? ` [${rule.globs.join(", ")}]` : ""} — \`${ANVIL_STATE_DIR}/harness/rules/${rule.language}/${rule.id}.md\``
      );
    }
    lines.push("");
  }
  // A lean index: this block loads into every session of every tool that reads it,
  // so it names each item with a short "when to use" and points at the file for the rest.
  if (agents.length) {
    lines.push(
      "### Specialist roles",
      "",
      `When a task matches a role, read \`${ANVIL_STATE_DIR}/harness/agents/<role>.md\` and follow it.`,
      ""
    );
    for (const agent of agents) lines.push(`- **${agent.id}**: ${brief(agent.description)}`);
    lines.push("");
  }
  if (commands.length) {
    lines.push(
      "### Workflows",
      "",
      `Run a workflow by reading \`${ANVIL_STATE_DIR}/harness/commands/<name>.md\`: ${commands.map((command) => `\`${command.id}\``).join(", ")}.`,
      ""
    );
  }
  if (skills.length) {
    lines.push(`### Skills (in \`${skillsPath}\`, load when relevant)`, "");
    for (const skill of skills) lines.push(`- **anvil-${skill.id}**: ${brief(skill.description)}`);
    lines.push("");
  }
  return lines.join("\n").trimEnd();
}

export async function buildInstallPlan(options: InstallOptions): Promise<InstallPlan> {
  const projectRoot = path.resolve(options.projectPath);
  const catalog = options.catalog ?? (await loadHarnessCatalog());
  const profile = options.profile ?? "standard";
  const targets = options.targets?.length ? normalizeHarnessTargets(options.targets) : [...DEFAULT_TARGETS];
  const languages = options.languages ?? (profile === "full" ? undefined : await detectProjectLanguages(projectRoot));
  const selected = selectCatalogItems(catalog, languages ? { profile, languages } : { profile });
  const extras = [...new Set(options.extras ?? [])].sort();
  const extraItems: CatalogItem[] = [];
  for (const extra of extras) {
    const match = /^(agent|skill|command|rule):([a-z0-9][a-z0-9/-]{0,80})$/.exec(extra);
    if (!match) throw new Error(`--with expects kind:id (e.g. skill:django-patterns), got "${extra}".`);
    const [, kind, id] = match;
    const item = catalog.items.find(
      (candidate) =>
        candidate.kind === kind && (candidate.id === id || `${candidate.language ?? ""}/${candidate.id}` === id)
    );
    if (!item) {
      throw new Error(
        `No ${kind} "${id}" in the ANVIL catalog. Try \`anvil consult\` or \`anvil catalog --kind ${kind}\`.`
      );
    }
    extraItems.push(item);
  }
  const items = [...selected, ...extraItems.filter((item) => !selected.includes(item))];
  const resolvedLanguages =
    languages ??
    [
      ...new Set(
        items.filter((i) => i.kind === "rule" && i.language && i.language !== "common").map((i) => i.language as string)
      ),
    ].sort();

  const files = new Map<string, PlannedFile>();
  const add = (file: PlannedFile, item: CatalogItem) => {
    const existing = files.get(file.path);
    if (existing) {
      if (existing.content !== file.content) throw new Error(`Install plan has conflicting content for ${file.path}.`);
      for (const target of file.targets) if (!existing.targets.includes(target)) existing.targets.push(target);
      return;
    }
    files.set(file.path, { ...file, item: `${item.kind}:${item.language ? item.language + "/" : ""}${item.id}` });
  };

  const blocks = new Map<string, PlannedBlock>();
  for (const target of targets) {
    for (const item of items) for (const file of renderTarget(target, item)) add(file, item);
    for (const blockPath of TARGET_BLOCK_FILES[target] ?? []) {
      const existing = blocks.get(blockPath);
      if (existing) existing.targets.push(target);
      else {
        blocks.set(blockPath, {
          path: blockPath,
          content: instructionsBlock(items, ".agents/skills"),
          targets: [target],
        });
      }
    }
  }

  return {
    profile,
    targets,
    languages: resolvedLanguages,
    files: [...files.values()].sort((a, b) => a.path.localeCompare(b.path)),
    blocks: [...blocks.values()].sort((a, b) => a.path.localeCompare(b.path)),
    itemCount: items.length,
    extras,
  };
}

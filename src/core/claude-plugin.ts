import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadHarnessCatalog, type CatalogItem, type HarnessCatalog } from "./harness-catalog.js";
import { claudeHookEntries } from "./harness-hooks.js";
import { NPM_PACKAGE } from "./harness-installer/types.js";

/**
 * Packages the ANVIL catalog as a Claude Code plugin, so users can install
 * every agent, skill, command, rule, Guard hook and the MCP server with
 * `/plugin marketplace add AdityaaaTiwari/ANVIL` and `/plugin install anvil@anvil`.
 *
 * The plugin is generated from `catalog/` and committed under `plugin/`.
 * `anvil plugin build --check` (run in CI) fails when the two drift.
 */

export const PLUGIN_NAME = "anvil";
export const PLUGIN_DIR = "plugin";

export interface PluginFile {
  /** Path relative to the plugin root, with forward slashes. */
  path: string;
  content: string;
}

export interface PluginBuild {
  files: PluginFile[];
  counts: { agents: number; skills: number; commands: number; ruleSkills: number };
}

const GENERATED = "<!-- Generated by `anvil plugin build` from catalog/. Edit the catalog, not this file. -->\n\n";

function yamlValue(value: string): string {
  return /^[\w .,()/'-]*$/.test(value) && !value.includes(": ") ? value : JSON.stringify(value);
}

function frontmatter(entries: Array<[string, string | undefined]>): string {
  const lines = entries
    .filter(([, value]) => value !== undefined && value !== "")
    .map(([key, value]) => `${key}: ${yamlValue(value as string)}`);
  return `---\n${lines.join("\n")}\n---\n\n`;
}

function markdown(entries: Array<[string, string | undefined]>, body: string): string {
  return frontmatter(entries) + GENERATED + body.trim() + "\n";
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2) + "\n";
}

/** Pinned launcher so a plugin install always runs the matching ANVIL release. */
function launcher(version: string): { command: string; args: string[] } {
  return { command: "npx", args: ["-y", `${NPM_PACKAGE}@${version}`] };
}

function ruleSkills(rules: CatalogItem[]): PluginFile[] {
  const groups = new Map<string, CatalogItem[]>();
  for (const rule of rules) {
    const language = rule.language ?? "common";
    groups.set(language, [...(groups.get(language) ?? []), rule]);
  }
  return [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([language, items]) => {
      const sorted = [...items].sort((a, b) => a.id.localeCompare(b.id));
      const globs = [...new Set(sorted.flatMap((item) => item.globs ?? []))];
      const scope =
        language === "common"
          ? "every change in any language"
          : `${language} code${globs.length ? ` (${globs.slice(0, 4).join(", ")})` : ""}`;
      const body = [
        `# ANVIL rules: ${language}`,
        "",
        `Follow these rules for ${scope}.`,
        "",
        ...sorted.map((item) => `## ${item.name}\n\n${item.body.trim()}\n`),
      ].join("\n");
      return {
        path: `skills/rules-${language}/SKILL.md`,
        content: markdown(
          [
            ["name", `rules-${language}`],
            ["description", `ANVIL coding rules for ${scope}: ${sorted.map((item) => item.name).join(", ")}.`],
          ],
          body
        ),
      };
    });
}

export function renderClaudePlugin(catalog: HarnessCatalog, version: string): PluginBuild {
  const items = [...catalog.items].sort((a, b) => a.kind.localeCompare(b.kind) || a.id.localeCompare(b.id));
  const agents = items.filter((item) => item.kind === "agent");
  const skills = items.filter((item) => item.kind === "skill");
  const commands = items.filter((item) => item.kind === "command");
  const rules = ruleSkills(items.filter((item) => item.kind === "rule"));
  const run = launcher(version);
  const base = [run.command, ...run.args].join(" ");

  const files: PluginFile[] = [
    {
      path: ".claude-plugin/plugin.json",
      content: json({
        name: PLUGIN_NAME,
        displayName: "ANVIL",
        version,
        description:
          "Deterministic verification layer for AI coding agents: Guard hooks, a pre-stop quality gate, " +
          `${agents.length} specialist agents, ${skills.length + rules.length} skills, ` +
          `${commands.length} commands and the read-only ANVIL MCP server.`,
        author: { name: "Aditya Tiwari", url: "https://github.com/AdityaaaTiwari" },
        homepage: "https://github.com/AdityaaaTiwari/ANVIL",
        repository: "https://github.com/AdityaaaTiwari/ANVIL",
        license: "MIT",
        keywords: ["verification", "guard", "security", "code-review", "agents", "skills", "mcp"],
      }),
    },
    {
      path: ".mcp.json",
      content: json({ mcpServers: { anvil: { command: run.command, args: [...run.args, "mcp", "start"] } } }),
    },
    {
      path: "hooks/hooks.json",
      content: json({
        hooks: Object.fromEntries(
          claudeHookEntries(base).map((entry) => [
            entry.event,
            [
              {
                ...(entry.matcher ? { matcher: entry.matcher } : {}),
                hooks: [{ type: "command", command: entry.command, timeout: entry.timeout }],
              },
            ],
          ])
        ),
      }),
    },
    ...agents.map((item) => ({
      path: `agents/${item.id}.md`,
      content: markdown(
        [
          ["name", item.id],
          ["description", item.description],
          ["tools", item.tools?.join(", ")],
        ],
        item.body
      ),
    })),
    ...skills.map((item) => ({
      path: `skills/${item.id}/SKILL.md`,
      content: markdown(
        [
          ["name", item.id],
          ["description", item.description],
        ],
        item.body
      ),
    })),
    ...commands.map((item) => ({
      path: `commands/${item.id}.md`,
      content: markdown(
        [
          ["description", item.description],
          ["argument-hint", item.argumentHint],
        ],
        item.body
      ),
    })),
    ...rules,
  ];

  return {
    // Catalog files are checked out with CRLF on Windows; always emit LF so every OS builds the same plugin.
    files: files
      .map((file) => ({ ...file, content: file.content.replace(/\r\n/g, "\n") }))
      .sort((a, b) => a.path.localeCompare(b.path)),
    counts: { agents: agents.length, skills: skills.length, commands: commands.length, ruleSkills: rules.length },
  };
}

/** The marketplace file at the repository root that points Claude Code at `plugin/`. */
export function renderMarketplace(version: string): string {
  return json({
    name: PLUGIN_NAME,
    owner: { name: "Aditya Tiwari", url: "https://github.com/AdityaaaTiwari" },
    metadata: { description: "ANVIL: the deterministic verification layer for AI coding agents." },
    plugins: [
      {
        name: PLUGIN_NAME,
        source: `./${PLUGIN_DIR}`,
        description:
          "Guard hooks, a pre-stop quality gate, specialist agents, skills, commands and the ANVIL MCP server.",
        version,
        category: "development",
      },
    ],
  });
}

async function listFiles(root: string, relative = ""): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(path.join(root, relative), { withFileTypes: true });
  } catch {
    return [];
  }
  const files: string[] = [];
  for (const entry of entries) {
    const child = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listFiles(root, child)));
    else if (entry.isFile()) files.push(child);
  }
  return files;
}

export interface PluginSyncResult {
  build: PluginBuild;
  /** Files that would be created, changed or removed. Empty means in sync. */
  drift: string[];
}

/**
 * Writes (or, with `check`, only compares) `plugin/` and
 * `.claude-plugin/marketplace.json` under `repoRoot`.
 */
export async function syncClaudePlugin(
  repoRoot: string,
  version: string,
  options: { check?: boolean; catalog?: HarnessCatalog } = {}
): Promise<PluginSyncResult> {
  const catalog = options.catalog ?? (await loadHarnessCatalog());
  const build = renderClaudePlugin(catalog, version);
  const pluginRoot = path.join(repoRoot, PLUGIN_DIR);
  const wanted = new Map<string, string>(build.files.map((file) => [`${PLUGIN_DIR}/${file.path}`, file.content]));
  wanted.set(".claude-plugin/marketplace.json", renderMarketplace(version));

  const drift: string[] = [];
  for (const [relative, content] of wanted) {
    let current: string | undefined;
    try {
      // Git on Windows may check files out with CRLF; compare content, not line endings.
      current = (await readFile(path.join(repoRoot, relative), "utf8")).replace(/\r\n/g, "\n");
    } catch {
      current = undefined;
    }
    if (current === content) continue;
    drift.push(current === undefined ? `+ ${relative}` : `~ ${relative}`);
    if (!options.check) {
      await mkdir(path.dirname(path.join(repoRoot, relative)), { recursive: true });
      await writeFile(path.join(repoRoot, relative), content, "utf8");
    }
  }
  for (const existing of await listFiles(pluginRoot)) {
    const relative = `${PLUGIN_DIR}/${existing}`;
    if (wanted.has(relative)) continue;
    drift.push(`- ${relative}`);
    if (!options.check) await rm(path.join(repoRoot, relative));
  }
  return { build, drift: drift.sort() };
}
